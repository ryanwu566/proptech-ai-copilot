export const DEFAULT_LOCALE: ExperienceLocale = "zh-TW";
export const LOCALE_LABELS: Record<ExperienceLocale, string> = { "zh-TW": "繁體中文", en: "English", ja: "日本語", ko: "한국어" };

export function normalizeExperienceLocale(value: string | null | undefined): ExperienceLocale {
  return SUPPORTED_LOCALES.includes(value as ExperienceLocale) ? value as ExperienceLocale : DEFAULT_LOCALE;
}

export function translateExperience(locale: ExperienceLocale, key: TranslationKey): string {
  return getExperienceOverride(locale, key) ?? resources[locale][key] ?? resources[DEFAULT_LOCALE][key] ?? key;
}

export function getExperienceLocaleCoverage(): Record<ExperienceLocale, { total: number; translated: number; missing: readonly TranslationKey[] }> {
  const keys = Object.keys(canonicalResource) as TranslationKey[];
  const coverage = {} as Record<ExperienceLocale, { total: number; translated: number; missing: readonly TranslationKey[] }>;
  for (const locale of SUPPORTED_LOCALES) {
    const missing = keys.filter((key) => !getExperienceOverride(locale, key) && (!resources[locale][key] || resources[locale][key] === resources[DEFAULT_LOCALE][key]));
    coverage[locale] = { total: keys.length, translated: keys.length - missing.length, missing };
  }
  return coverage;
}

export function formatExperienceNumber(value: number, locale: ExperienceLocale): string {
  return new Intl.NumberFormat(locale).format(value);
}

export function formatExperiencePercent(value: number, locale: ExperienceLocale): string {
  return new Intl.NumberFormat(locale, { style: "percent", maximumFractionDigits: 1 }).format(value / 100);
}

export function formatExperienceDate(value: string | number | Date, locale: ExperienceLocale): string {
  return new Intl.DateTimeFormat(locale, { dateStyle: "medium" }).format(new Date(value));
}
